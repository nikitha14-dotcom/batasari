"""Copy the router prompt and fixed facts out of the DS harness into the gateway.

Reads the harness with ast and never runs it. Re-run after the DS team ships a
new harness, then register a NEW router version (ADR 0012).

Usage: python scripts/extract_router_prompts.py <eval_harness_final.py> <out.py>
"""
import ast
import sys
from pathlib import Path

NAMES = [
    "ROUTER_INSTRUCTION",
    "ROUTER_CATEGORY_INSTRUCTIONS",
    "CANONICAL_FACTS",
    "PRODUCT_CATEGORIES",
    "ALLOWED_CLASSIFICATIONS",
    "ALLOWED_SAFETY_ACTIONS",
    "ALLOWED_SAFETY_CATEGORIES",
]


def _literal(node):
    """Evaluate the plain literals the harness uses, without running it."""
    if isinstance(node, ast.Constant):
        return node.value
    if isinstance(node, ast.Dict):
        return {_literal(k): _literal(v) for k, v in zip(node.keys, node.values)}
    if isinstance(node, ast.List):
        return [_literal(e) for e in node.elts]
    if isinstance(node, ast.Tuple):
        return tuple(_literal(e) for e in node.elts)
    if isinstance(node, ast.Set):
        return {_literal(e) for e in node.elts}
    if (
        isinstance(node, ast.Call)
        and not node.args
        and not node.keywords
        and isinstance(node.func, ast.Attribute)
        and node.func.attr in ("strip", "lstrip", "rstrip")
    ):
        return getattr(_literal(node.func.value), node.func.attr)()
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        return _literal(node.left) + _literal(node.right)
    raise ValueError(f"unsupported expression: {type(node).__name__}")


def _render(name, value):
    if isinstance(value, (set, frozenset)):
        return f"{name} = frozenset({sorted(value)!r})"
    return f"{name} = {value!r}"


def main(harness_path: str, out_path: str) -> None:
    tree = ast.parse(Path(harness_path).read_text(encoding="utf-8"))
    found = {}
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id in NAMES
        ):
            try:
                found[node.targets[0].id] = _literal(node.value)
            except ValueError as exc:
                sys.exit(f"{node.targets[0].id}: {exc}")
    missing = [name for name in NAMES if name not in found]
    if missing:
        sys.exit(f"Not found in the harness: {missing}")
    out = [
        "# ruff: noqa",
        '"""Router prompt and fixed facts copied from the DS harness.',
        "",
        "Generated by scripts/extract_router_prompts.py. Do not edit by hand.",
        '"""',
        "",
    ]
    for name in NAMES:
        out.append(_render(name, found[name]))
        out.append("")
    Path(out_path).write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"Wrote {len(NAMES)} constants to {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
