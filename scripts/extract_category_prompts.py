"""Copy the answer prompts out of the DS harness into the gateway as plain text.

Reads the harness with ast and never runs it, so it needs no API keys. Re-run
after the DS team ships a new harness, then register a NEW prompt version
(ADR 0012: never edit a registered version).

Usage: python scripts/extract_category_prompts.py <eval_harness_final.py> <out.py>
"""
import ast
import sys
from pathlib import Path

NAMES = [
    "CORE_ANSWER_INSTRUCTION",
    "HOUSING_CATEGORY_INSTRUCTION",
    "WORK_CATEGORY_INSTRUCTION",
    "FAMILY_CATEGORY_INSTRUCTION",
    "EDUCATION_CATEGORY_INSTRUCTION",
    "FINANCE_CATEGORY_INSTRUCTION",
    "DAILY_NEEDS_CATEGORY_INSTRUCTION",
    "HEALTH_CATEGORY_INSTRUCTION",
    "IMMIGRATION_CATEGORY_INSTRUCTION",
    "CITY_CATEGORY_INSTRUCTION",
    "MOVING_SHIPPING_CATEGORY_INSTRUCTION",
    "CHECKLIST_CATEGORY_INSTRUCTION",
    "OTHER_CATEGORY_INSTRUCTION",
    "LIMITED_ANSWER_INSTRUCTION",
    "CONFIDENCE_OUTPUT_INSTRUCTION",
]


def _string_value(node):
    """The harness writes a raw triple-quoted string, with or without .strip()."""
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if (
        isinstance(node, ast.Call)
        and not node.args
        and not node.keywords
        and isinstance(node.func, ast.Attribute)
        and node.func.attr in ("strip", "lstrip", "rstrip")
        and isinstance(node.func.value, ast.Constant)
        and isinstance(node.func.value.value, str)
    ):
        return getattr(node.func.value.value, node.func.attr)()
    return None


def main(harness_path: str, out_path: str) -> None:
    tree = ast.parse(Path(harness_path).read_text(encoding="utf-8"))
    found = {}
    for node in tree.body:
        if (
            isinstance(node, ast.Assign)
            and len(node.targets) == 1
            and isinstance(node.targets[0], ast.Name)
            and node.targets[0].id in NAMES
        ):
            value = _string_value(node.value)
            if value is not None:
                found[node.targets[0].id] = value
    missing = [name for name in NAMES if name not in found]
    if missing:
        sys.exit(f"Not found as plain strings in the harness: {missing}")
    out = [
        "# ruff: noqa",
        '"""Answer prompts copied from the DS harness.',
        "",
        "Generated by scripts/extract_category_prompts.py. Do not edit by hand.",
        '"""',
        "",
    ]
    for name in NAMES:
        text = found[name]
        if '"""' in text or text.endswith("\\"):
            sys.exit(f"{name} cannot be written as a raw string")
        out.append(f'{name} = r"""{text}"""')
        out.append("")
    Path(out_path).write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"Wrote {len(NAMES)} prompts to {out_path}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
